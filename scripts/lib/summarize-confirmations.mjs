/**
 * Pure aggregation for "Still there?" reports, kept apart from the script so
 * it can be tested without a database.
 *
 * Rules:
 *   * Only rows inside the window count (default 90 days).
 *   * One vote per device per entry: its latest row wins. A device that said
 *     "seen" and later "missing" counts once, as missing.
 *   * lastSeenISO / lastMissingISO are the newest of those winning votes.
 *   * Rows for entries not in knownIds are dropped and reported back.
 */
const DAY_MS = 24 * 60 * 60 * 1000;

export function summarizeConfirmations(rows, { knownIds, now = Date.now(), windowDays = 90 } = {}) {
  const cutoff = now - windowDays * DAY_MS;
  const latest = new Map();
  const unknown = new Set();

  for (const row of rows ?? []) {
    const at = Date.parse(row.created_at);
    if (Number.isNaN(at) || at < cutoff || at > now) continue;
    if (row.status !== "seen" && row.status !== "missing") continue;
    if (knownIds && !knownIds.has(row.entry_id)) {
      unknown.add(row.entry_id);
      continue;
    }
    const key = `${row.entry_id}\u0000${row.device_id}`;
    const prev = latest.get(key);
    if (!prev || at > prev.at) latest.set(key, { entryId: row.entry_id, status: row.status, at });
  }

  const summaries = {};
  for (const vote of latest.values()) {
    const s = (summaries[vote.entryId] ??= { seen: 0, missing: 0 });
    const iso = new Date(vote.at).toISOString();
    if (vote.status === "seen") {
      s.seen += 1;
      if (!s.lastSeenISO || vote.at > Date.parse(s.lastSeenISO)) s.lastSeenISO = iso;
    } else {
      s.missing += 1;
      if (!s.lastMissingISO || vote.at > Date.parse(s.lastMissingISO)) s.lastMissingISO = iso;
    }
  }

  const sorted = Object.fromEntries(Object.keys(summaries).sort().map((id) => [id, summaries[id]]));
  return { summaries: sorted, unknownEntryIds: [...unknown].sort() };
}

/** The TypeScript module the app imports. */
export function renderGeneratedModule(summaries, pulledAtISO) {
  const body = Object.entries(summaries)
    .map(([id, s]) => {
      const fields = [`seen: ${s.seen}`, `missing: ${s.missing}`];
      if (s.lastSeenISO) fields.push(`lastSeenISO: ${JSON.stringify(s.lastSeenISO)}`);
      if (s.lastMissingISO) fields.push(`lastMissingISO: ${JSON.stringify(s.lastMissingISO)}`);
      return `  ${JSON.stringify(id)}: { ${fields.join(", ")} },`;
    })
    .join("\n");

  return [
    "/**",
    " * Generated by scripts/pull-confirmations.mjs. Do not edit by hand.",
    " * One vote per device (its latest) over the last 90 days.",
    " * Run `npm run confirmations:pull` to refresh.",
    " */",
    'import type { ConfirmationSummary } from "./confirmations";',
    "",
    `export const CONFIRMATIONS_PULLED_AT_ISO: string | undefined = ${JSON.stringify(pulledAtISO)};`,
    "",
    body.length > 0
      ? `export const confirmations: Record<string, ConfirmationSummary> = {\n${body}\n};`
      : "export const confirmations: Record<string, ConfirmationSummary> = {};",
    "",
  ].join("\n");
}
